struct Unit {
    Ctld ctld;
    Mesh mesh;
    std::vector<ContactPoint> points;
};

Vec3 pos_of(const Mat4& m) { return {m.at(0, 3), m.at(1, 3), m.at(2, 3)}; }

// Body-origin ground following (the port's stand-in for FollowGround): keeps the unit on the landscape.
void follow_ground(UnitMotion& m, const TerrainGround& ground) {
    const Vec3 p = pos_of(m.output_matrix());
    if (auto g = ground.probe(p + Vec3{0, 0, 7.f}, 15.f)) m.apply_offset({0, 0, g->z - p.z});
}

void test_tut2(const std::filesystem::path& game) {
    std::printf("unit AI on Tut_2\n");
    const auto mapf = resolve_path(game, "DATA/MAPS/Tut_2/Land.map");
    const auto mshf = resolve_path(game, "DATA/MAPS/Tut_2/Land.msh");
    const auto tmaf = resolve_path(game, "MISSIONS/CAMPAIGN/CAMPAIGN.00/Mission.02/data.tma");
    if (!mapf || !mshf || !tmaf) {
        CHECK(!"Tut_2 map / mission missing");
        return;
    }
    LandMap map = decode_landmap(read_file(*mapf));
    CHECK(map.areals.size() == 900 && map.cells_x == 128 && map.cells_y == 128);
    std::size_t walkable = 0, anchors_vertex_box = 0, anchors_land_box = 0;
    for (const auto& a : map.areals) walkable += a.walkable != 0;
    CHECK(walkable == 104);
    for (std::uint32_t i = 0; i < map.areals.size(); ++i)
        anchors_vertex_box += map.areal_at(map.areals[i].anchor.x, map.areals[i].anchor.y) == i;
    const Terrain terrain = decode_terrain(read_file(*mshf));
    const TerrainGround ground(terrain);
    map.set_bounds(ground.bounds_min().x, ground.bounds_min().y, ground.bounds_max().x, ground.bounds_max().y);
    for (std::uint32_t i = 0; i < map.areals.size(); ++i)
        anchors_land_box += map.areal_at(map.areals[i].anchor.x, map.areals[i].anchor.y) == i;
    std::printf("  anchors found in their own areal: %zu (areal box), %zu (landscape box)\n", anchors_vertex_box,
                anchors_land_box);
    CHECK(anchors_land_box > 850);
    const ArealGraph graph = ArealGraph::build(map);
    const mission::Tma tma = mission::decode_tma(read_file(*tmaf));

    AssetLibrary lib(game);
    // ---- a warbot chassis (r_l_01) with a Go order from the hero's spawn ----
    {
        const NResEntry *ce = lib.find("bases.rlb", "r_l_01.ctl"), *me = lib.find("bases.rlb", "r_l_01.msh"),
                        *pe = lib.find("bases.rlb", "r_l_01.cpt");
        if (!ce || !me || !pe) {
            CHECK(!"r_l_01 missing");
            return;
        }
        const Ctld ctld = decode_ctld(ce->data);
        const Mesh mesh = decode_mesh(me->data);
        const auto points = decode_ctpt(pe->data);
        Vec3 spawn{300.3f, 556.1f, 0};
        for (const auto& o : tma.objects)
            if (o.resource.find("HERO") != std::string::npos) spawn = {o.position[0], o.position[1], 0};
        const auto from = map.areal_at(spawn.x, spawn.y);
        CHECK(from && map.areals[*from].walkable);
        if (!from) return;
        // Target: the farthest anchor within 250 m that the graph reaches.
        std::vector<int> seen(map.areals.size(), 0);
        std::vector<std::uint32_t> stack{*from};
        seen[*from] = 1;
        std::uint32_t best = *from;
        while (!stack.empty()) {
            const std::uint32_t n = stack.back();
            stack.pop_back();
            const float d = dist2d(map.areals[n].anchor, spawn);
            if (d < 250 && d > dist2d(map.areals[best].anchor, spawn)) best = n;
            for (const auto& e : graph.nodes[n].edges)
                if (!seen[e.to]) seen[e.to] = 1, stack.push_back(e.to);
        }
        const Vec3 target = map.areals[best].anchor;
        std::printf("  r_l_01: from (%.0f, %.0f) to (%.0f, %.0f), %.0f m\n", spawn.x, spawn.y, target.x, target.y,
                    dist2d(spawn, target));
        CHECK(dist2d(spawn, target) > 100);

        UnitMotion motion(ctld, mesh, points);
        Mat4 pose = Mat4::translation(spawn);
        if (auto g = ground.probe(spawn + Vec3{0, 0, 1000}, 2000.f)) pose.at(2, 3) = g->z;
        motion.start(0, pose);
        MsvcRand rng;
        AiUnit unit(motion, map, graph, [&] { return rng(); });
        unit.set_ground_height([&](float x, float y) {
            auto g = ground.probe({x, y, 1000}, 2000.f);
            return g ? g->z : 0.f;
        });
        unit.give_order_go(target);
        float t = 0, arrived = -1, max_speed = 0;
        for (; t < 120000 && arrived < 0; t += 33) {
            unit.update(t);
            follow_ground(motion, ground);
            const Vec3 v = motion.world_velocity();
            max_speed = std::max(max_speed, std::hypot(v.x, v.y));
            if (unit.current_order() == kOrderPatrol) arrived = t;
        }
        const Vec3 end = unit.position();
        std::printf("  r_l_01: Go done at %.1f s, %.1f m from the target, route %zu areals, %d re-plans, top speed "
                    "%.1f m/s, cruise %.1f\n",
                    arrived / 1000, dist2d(end, target), unit.walker().route().size(), unit.walker().replans(), max_speed,
                    unit.walker().cruise_speed());
        CHECK(arrived > 0 && dist2d(end, target) < 30);
        // A lone Go leaves a patrol (radius 150) around the target behind: the unit keeps walking.
        const Vec3 at_done = end;
        for (float t2 = t; t2 < t + 20000; t2 += 33) {
            unit.update(t2);
            follow_ground(motion, ground);
        }
        CHECK(unit.current_order() == kOrderPatrol && dist2d(unit.position(), at_done) > 10);
    }

    // ---- an animal (tent.dat) migrating in its clan's areals ----
    // ---- the animals (tent.dat) migrating in their clan's areals, for several seeds ----
    {
        std::vector<const mission::TmaObject*> tents;
        for (const auto& o : tma.objects)
            if (o.resource.find("tent.dat") != std::string::npos) tents.push_back(&o);
        const mission::TmaClan* clan = nullptr;
        for (const auto& c : tma.clans)
            if (!c.spatial.empty()) clan = &c;
        auto model = tents.empty() ? std::nullopt : load_unit_model(lib, tents[0]->resource);
        const NResEntry* ce = model ? lib.find(model->ctl_archive, model->ctl_entry) : nullptr;
        if (tents.size() != 2 || !clan || !ce) {
            CHECK(!"tents / animal clan / their motion graph missing");
            return;
        }
        const Ctld ctld = decode_ctld(ce->data);
        std::vector<ContactPoint> points;
        const std::string base = model->ctl_entry.substr(0, model->ctl_entry.rfind('.'));
        if (const NResEntry* pe = lib.find(model->ctl_archive, base + ".cpt")) points = decode_ctpt(pe->data);
        for (const std::uint32_t seed : {1u, 7u, 42u}) {
            ClanMigration mig{clan->spatial, {}, -1}; // shared by the clan's units
            MsvcRand rng{seed};                        // one CRT generator for the whole run
            std::vector<std::unique_ptr<UnitMotion>> motions;
            std::vector<std::unique_ptr<AiUnit>> units;
            for (const auto* tent : tents) {
                motions.push_back(std::make_unique<UnitMotion>(ctld, model->parts.front().model.mesh, points));
                motions.back()->start(0, tma_placement(*tent));
                // a_a_l3 is an animal flyer (control-physics.md "Flying units"; its chassis sheet is not
                // traced: chas_fly assumed, CanFly 1, WalkChassis 0): the pilot also commands body x and z,
                // and the walker goes straight to the target without the areal graph.
                units.push_back(std::make_unique<AiUnit>(*motions.back(), map, graph, [&] { return rng(); },
                                                         AiUnitConfig{true, false, true}));
                units.back()->set_ground_height([&](float x, float y) {
                    auto g = ground.probe({x, y, 1000}, 2000.f);
                    return g ? g->z : 0.f;
                });
                units.back()->set_migration(&mig);
            }
            std::vector<Vec3> start, last;
            std::vector<float> travelled(units.size(), 0), farthest(units.size(), 0);
            std::vector<int> busy(units.size(), 0);
            for (const auto& u : units) start.push_back(u->position()), last.push_back(u->position());
            int ticks = 0;
            for (float t = 0; t < 90000; t += 33, ++ticks)
                for (std::size_t i = 0; i < units.size(); ++i) {
                    units[i]->update(t);
                    // FollowGround for a flyer only keeps it above the ground.
                    UnitMotion& m = *motions[i];
                    const Vec3 p = pos_of(m.output_matrix());
                    if (auto g = ground.probe(p + Vec3{0, 0, 1000}, 2000.f); g && p.z < g->z + 1)
                        m.apply_offset({0, 0, g->z + 1 - p.z});
                    const Vec3 q = units[i]->position();
                    travelled[i] += dist2d(q, last[i]);
                    farthest[i] = std::max(farthest[i], dist2d(q, start[i]));
                    last[i] = q;
                    busy[i] += units[i]->moving();
                }
            for (std::size_t i = 0; i < units.size(); ++i) {
                std::printf("  tent %zu, seed %2u: clan areal (last pick) %d, flew %.0f m over 90 s, at most %.0f m from the "
                            "start, walker busy %d%% of ticks, %d re-plans\n",
                            i, seed, mig.current, travelled[i], farthest[i], busy[i] * 100 / ticks, units[i]->walker().replans());
                CHECK(units[i]->current_order() == kOrderMigrate);
                CHECK(travelled[i] > 20 && busy[i] > 0);
            }
        }
    }
}

