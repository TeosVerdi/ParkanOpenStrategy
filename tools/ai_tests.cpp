bool near(float a, float b, float tol) { return std::abs(a - b) <= tol; }

void test_msvc_rand() {
    MsvcRand r; // srand(1): the documented CRT sequence
    CHECK(r() == 41 && r() == 18467 && r() == 6334 && r() == 26500);
}

// A 5-node graph:  0 —1— 1 —1— 3 —1— 4,  0 —1— 2 —5— 3.
ArealGraph tiny_graph() {
    ArealGraph g;
    const Vec3 c[5] = {{0, 0, 0}, {1, 0, 0}, {1, 1, 0}, {2, 0, 0}, {3, 0, 0}};
    for (const Vec3& p : c) g.nodes.push_back({p, {}});
    const auto link = [&](std::uint32_t a, std::uint32_t b, float cost, std::uint32_t flags = 0xffff) {
        g.nodes[a].edges.push_back({b, flags, cost});
        g.nodes[b].edges.push_back({a, flags, cost});
    };
    link(0, 1, 1);
    link(1, 3, 1);
    link(3, 4, 1);
    link(0, 2, 1);
    link(2, 3, 5);
    return g;
}

void test_areal_search() {
    std::printf("areal search\n");
    const RandomSource zero = [] { return 0; };
    ArealGraph g = tiny_graph();
    CHECK(search_path(g, 0, 4, false, zero) == (std::vector<std::uint32_t>{0, 1, 3, 4}));
    CHECK(search_path(g, 2, 2, false, zero) == (std::vector<std::uint32_t>{2}));
    // Closed (0x20000) and flyer-only (0x10000) edges.
    for (auto& e : g.nodes[1].edges)
        if (e.to == 3) e.flags = 0x20000;
    CHECK(search_path(g, 0, 4, false, zero) == (std::vector<std::uint32_t>{0, 2, 3, 4}));
    for (auto& e : g.nodes[2].edges)
        if (e.to == 3) e.flags = 0x10000;
    CHECK(search_path(g, 0, 4, false, zero).empty());
    CHECK(search_path(g, 0, 4, true, zero) == (std::vector<std::uint32_t>{0, 2, 3, 4}));

    // The search stops when the goal is first generated, not popped: a direct 0–4 edge of cost 100
    // wins because 4 is generated by the very first expansion.
    g = tiny_graph();
    g.nodes[0].edges.push_back({4, 0xffff, 100});
    CHECK(search_path(g, 0, 4, false, zero) == (std::vector<std::uint32_t>{0, 4}));

    // The perturbation multiplies the whole accumulated g by (1 + r01·0.7) per relaxation. With the
    // detour 2–3 costing 2, plain A* takes 0-1-3-4 (f: 1 → 3, 2 → 3.24, then 3 via 1 at f = 3). A rigged
    // rand() makes the detour win: 0→1 drawn high (g = 1.7, f = 3.7), 0→2 low (g = 1, f = 3.24); 2 is
    // expanded first (2→0 rejected, 2→3: g = 3, f = 4), then 1 (1→0 rejected, 1→3 drawn high:
    // (1 + 1.7)·1.7 = 4.59 > 3, rejected), then 3, which generates the goal. Eight draws.
    g = tiny_graph();
    for (auto* n : {&g.nodes[2], &g.nodes[3]})
        for (auto& e : n->edges)
            if (e.to == 2 || e.to == 3) e.cost = 2;
    CHECK(search_path(g, 0, 4, false, zero) == (std::vector<std::uint32_t>{0, 1, 3, 4}));
    const int seq[] = {32767, 0, 0, 0, 0, 32767, 0, 0};
    int k = 0;
    const RandomSource rigged = [&] { return seq[k++ % 8]; };
    CHECK(search_path(g, 0, 4, false, rigged) == (std::vector<std::uint32_t>{0, 2, 3, 4}));
    CHECK(k == 8);
}

// CWizard on a straight segment: unit at the origin facing +y, one point 10 m ahead due in 2 s at 5 m/s.
void test_wizard() {
    std::printf("wizard\n");
    std::array<float, 27> body{};
    body[6] = 1, body[7] = 10, body[8] = 1, body[11] = 2;
    Wizard wz;
    wz.add_point({{0, 10, 0}, {0, 5, 0}, {0, 5, 0}, 2000, 0x3030});
    auto out = wz.takt(0, 100, Mat4::identity(), body);
    CHECK(out.has_value());
    // T = 2, Δ = (0,10,0), δ = (v1 − v0)·T = (0,10,0): c2 = (3Δ − δ)/T² = 5, c3 = (δ − 2Δ)/T³ = −1.25;
    // the velocity at mid-step τ = 0.05 s: (3·c3·τ + 2·c2)·τ = 0.490625 m/s forward.
    CHECK(out && near(out->linear.y, 0.490625f, 1e-5f) && out->linear.x == 0 && out->linear.z == 0);
    CHECK(out && out->yaw == 0); // heading straight ahead
    CHECK(wz.segment_start() == 0 && wz.segment_end() == 2000 && wz.point_count() == 1);
    // Halfway: p(1) = 5 + −1.25 = 3.75 m; the velocity at τ = 1.05: (3·−1.25·1.05 + 10)·1.05 = 6.365625.
    out = wz.takt(1000, 100, Mat4::translation({0, 3.75f, 0}), body);
    CHECK(near(wz.evaluated_position().y, 3.75f, 1e-5f));
    CHECK(out && near(out->linear.y, 6.365625f, 1e-4f));
    // A unit turned 90° left (forward = −x) sees the same world velocity as a sideways body x it may not
    // use (flags 0x3030), and turns right at the full rate: the error (π/2) exceeds L·rate = 0.2 rad.
    const Mat4 left = Mat4::rotation({0, 0, std::sqrt(0.5f), std::sqrt(0.5f)});
    out = wz.takt(1000, 100, left, body);
    CHECK(out && out->linear.x == 0 && near(out->linear.y, 0, 1e-5f) && out->yaw == -1);
    // A small error closes in one step. Linear heading (flag 1): lerp(d0, d1, τh/T) with τh = L = 0.1 s,
    // T = 1 s, d1 0.1 rad to the left: (−0.1·sin 0.1, 0.9 + 0.1·cos 0.1) is 0.009988 rad left of +y,
    // and the command is that angle / (L · body[11]) = 0.04994.
    Wizard w2;
    w2.add_point({{0, 100, 0}, {}, {-std::sin(0.1f), std::cos(0.1f), 0}, 1000, 0x3031});
    out = w2.takt(0, 100, Mat4::identity(), body);
    CHECK(out && near(out->yaw, 0.04994f, 2e-4f));
    // The segment end inside this step: the reached point is dropped, the route empties and the pilot
    // holds the current place (flags 0x3331: every axis forced to 0).
    out = wz.takt(1950, 100, Mat4::translation({0, 10, 0}), body);
    CHECK(wz.point_count() == 0 && wz.segment_end() == 2950 && (wz.segment_target().flags & 0x3331) == 0x3331);
    CHECK(out && out->linear.y == 0 && out->linear.x == 0 && out->linear.z == 0);
    // Nibble 5 (no negatives, replace by +max) and 6 (no positives, replace by −max).
    Wizard w3;
    w3.add_point({{0, -10, 0}, {0, -5, 0}, {0, 1, 0}, 2000, 0x0500 | 0x0060});
    out = w3.takt(0, 100, Mat4::identity(), body);
    CHECK(out && out->linear.y == 10 && out->linear.x == -1);
}

void test_landmap_synthetic() {
    LandAreal a;
    a.verts = {{0, 0, 0}, {10, 0, 0}, {10, 10, 0}, {0, 10, 0}};
    CHECK(a.contains(5, 5) && !a.contains(11, 5) && !a.contains(5, -1));
}

// Two 10 m squares side by side: areal 0 (x 0..10, walkable), areal 1 (x 10..20, not walkable).
LandMap two_squares() {
    LandMap m;
    for (int i = 0; i < 2; ++i) {
        LandAreal a;
        const float x0 = 10.f * float(i);
        a.verts = {{x0, 0, 0}, {x0 + 10, 0, 0}, {x0 + 10, 10, 0}, {x0, 10, 0}}; // CCW
        a.links = {{-1, -1}, {i == 0 ? 1 : -1, i == 0 ? 3 : -1}, {-1, -1}, {i == 1 ? 0 : -1, i == 1 ? 1 : -1}};
        a.anchor = {x0 + 5, 5, 0};
        a.walkable = i == 0;
        a.min_x = x0, a.max_x = x0 + 10, a.min_y = 0, a.max_y = 10;
        m.areals.push_back(a);
    }
    m.cells_x = m.cells_y = 1;
    m.cell_ids = {0, 1};
    m.cell_first = {0, 2};
    m.set_bounds(0, 0, 20, 10);
    return m;
}

// A target inside the unit's own areal: the route is that areal alone and the corridor the target
// (PlanGlobalPath with a one-node path goes to its tail), timed as one stopping point plus two holds.
// A flyer reaches a target the graph cannot (no edges out of an unwalkable areal) straight away.
void test_walker_targets() {
    std::printf("walker targets\n");
    const LandMap map = two_squares();
    const ArealGraph graph = ArealGraph::build(map);
    CHECK(graph.nodes[0].edges.empty() && graph.nodes[1].edges.empty()); // 1 is not walkable
    MTimer timer;
    Walker w(map, graph, [] { return 0; });
    w.max_speed = 10, w.min_speed = 0.5f;
    w.tick_timer = &timer;
    UnitState st{{2, 2, 0}, {}, {0, 1, 0}, 1000};
    w.unit_state = [&] { return st; };
    CHECK(w.set_target({7, 8, 0}, 10));
    CHECK(w.route() == std::vector<std::uint32_t>{0} && w.corridor().size() == 1);
    Wizard wz;
    w.on_behaviour_takt(wz);
    // One leg of √(25 + 36) = 7.81 m from rest (ground unit: end speed 0), t = 2·7.81 / max(10 + 0, 2):
    // 1562 ms, then the two holds at +500 / +700.
    CHECK(w.points().size() == 3 && wz.point_count() == 3 && !w.idle());
    CHECK(w.points().size() == 3 && w.points()[0].time == 1000 + 1562 && w.points()[2].time == 1000 + 1562 + 700);
    CHECK(w.points().size() == 3 && w.points()[0].vel.y == 0 && (wz.point(0).flags & 0x3030) == 0x3030);
    // Into the unwalkable areal: a ground unit cannot, a flyer goes straight (no route, no portals).
    CHECK(!w.set_target({15, 5, 0}, 10));
    w.can_fly = true, w.walk_chassis = false;
    CHECK(w.set_target({15, 5, 0}, 10));
    CHECK(w.route().empty() && w.corridor().size() == 1 && w.corridor()[0].pos.x == 15 && w.corridor()[0].areal == 1);
    st.pos = {15, 5, 0}; // a flyer standing in the unwalkable areal leaves it too
    CHECK(w.set_target({5, 5, 0}, 10) && w.corridor().size() == 1);
    // Off the grid: nothing to target.
    CHECK(!w.set_target({25, 5, 0}, 10));
}

